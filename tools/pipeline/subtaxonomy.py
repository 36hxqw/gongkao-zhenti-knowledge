def classify_sub(code, text):
    """返回 (sub_name, matched)。text 建议传 stem + 解析前 200 字。"""
    entries = SUB_TAXONOMY.get(code)
    if not entries:
        return "通用", False
    for name, pat in entries:
        if pat is None:
            return name, False
        if pat and __import__("re").search(pat, text or ""):
            return name, True
    return entries[-1][0], False


def sub_count():
    return sum(len(v) for v in SUB_TAXONOMY.values())
